// --- OTP verifications ------------------------------------------------------

export const otpVerifications = pgTable(
  "otp_verifications",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    /** E.164. */
    phone: text("phone").notNull(),
    /** Hash only. The plaintext code must never be persisted. */
    codeHash: text("code_hash").notNull(),
    attempts: integer("attempts").notNull().default(0),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    consumedAt: timestamp("consumed_at", { withTimezone: true }),
    ip: inet("ip"),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (table) => [
    index("otp_verifications_phone_idx").on(table.phone),
    index("otp_verifications_expires_at_idx").on(table.expiresAt),
  ],
);

// --- Payments ---------------------------------------------------------------

export const payments = pgTable(
  "payments",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    bookingId: uuid("booking_id")
      .notNull()
      .references(() => bookings.id, { onDelete: "cascade" }),
    /** e.g. "skipcash". */
    provider: text("provider").notNull(),
    /** The provider's own transaction id. */
    providerRef: text("provider_ref"),
    /** Minor units, same convention as bookings.price_*. */
    amount: integer("amount").notNull(),
    currency: text("currency").notNull().default("QAR"),
    status: paymentStatus("status").notNull().default("initiated"),
    /** Verbatim provider webhook body, kept for dispute resolution. */
    rawPayload: jsonb("raw_payload"),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  // A partial unique index on (provider, provider_ref) lives in
  // drizzle/0001_booking_locking.sql alongside the other partial indexes, so a
  // replayed provider webhook cannot create duplicate payment rows.
  (table) => [index("payments_booking_id_idx").on(table.bookingId)],
);

// --- Notifications (outbox) -------------------------------------------------

export const notifications = pgTable(
  "notifications",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    bookingId: uuid("booking_id").references(() => bookings.id, {
      onDelete: "cascade",
    }),
    channel: notificationChannel("channel").notNull(),
    recipientType: notificationRecipientType("recipient_type").notNull(),
    /** Email address or E.164 number. */
    recipient: text("recipient").notNull(),
    templateKey: text("template_key").notNull(),
    locale: text("locale").notNull().default("ar"),
    payload: jsonb("payload").notNull().default({}),
    status: notificationStatus("status").notNull().default("queued"),
    attempts: integer("attempts").notNull().default(0),
    /**
     * Raised by `resend_notification()` so a row that already burned its five
     * tries can genuinely go again when an admin asks.
     */
    maxAttempts: integer("max_attempts").notNull().default(5),
    lastError: text("last_error"),
    /**
     * Set when a worker takes the row and cleared when it finishes. A row that
     * still has this set long after `last_attempt_at` belonged to a worker that
     * died; `claim_notifications(limit, stale)` takes it back.
     */
    claimedAt: timestamp("claimed_at", { withTimezone: true }),
    lastAttemptAt: timestamp("last_attempt_at", { withTimezone: true }),
    /** Provider-side id of the delivered message, for support requests. */
    providerRef: text("provider_ref"),
    /** Doubles as the retry schedule: backoff pushes this into the future. */
    scheduledFor: timestamp("scheduled_for", { withTimezone: true })
      .notNull()
      .defaultNow(),
    sentAt: timestamp("sent_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (table) => [
    // The phase 7 worker polls exactly this: queued rows that are due.
    index("notifications_pending_idx").on(table.status, table.scheduledFor),
    index("notifications_booking_id_idx").on(table.bookingId),
    /**
     * The idempotency key from SRS 3.4: one message per booking, template and
     * recipient. Declared here so `pnpm db:generate` does not try to drop it;
     * the real definition is the partial index in
     * drizzle/0007_notifications.sql, which Drizzle cannot express (it is
     * `WHERE booking_id IS NOT NULL`).
     */
    uniqueIndex("notifications_dedupe_key").on(
      table.bookingId,
      table.templateKey,
      table.recipient,
    ),
  ],
);

// --- Settings (single row) --------------------------------------------------

export const settings = pgTable("settings", {
  /**
   * Constrained to 1 by a CHECK, so this table can only ever hold one row and
   * `select * from settings` is unambiguous.
   */
  id: integer("id").primaryKey().default(1),

  // Pricing, minor units.
  priceRental: integer("price_rental").notNull(),
  priceSetup: integer("price_setup").notNull(),
  priceDelivery: integer("price_delivery").notNull(),
  currency: text("currency").notNull().default("QAR"),

  /** Bookable setup times, Qatar wall clock, "HH:MM:SS". */
  availableStartTimes: text("available_start_times").array().notNull(),
  /** Minimum notice before the first slot of a day. */
  leadTimeHours: integer("lead_time_hours").notNull().default(24),
  /** How far ahead the calendar is open. */
  maxAdvanceDays: integer("max_advance_days").notNull().default(120),
  /** Checkout lock duration. */
  holdMinutes: integer("hold_minutes").notNull().default(10),

  adminNotificationEmails: text("admin_notification_emails")
    .array()
    .notNull()
    .default([]),
  /**
   * jsonb `[{en, ar}]` since migration 0012 — a text[] could only hold one
   * spelling, so an Arabic customer picked their area off an English chip.
   * The English name stays canonical: it is what `bookings.area` records.
   */
  serviceAreas: jsonb("service_areas")
    .$type<{ en: string; ar: string }[]>()
    .notNull()
    .default([]),

  /**
   * Terms & conditions, edited from the back office (migration 0014).
   *
   * Plain text, not HTML: an admin types into a textarea and the public page
   * renders paragraph-per-blank-line. Accepting markup here would mean an
   * admin could inject script into a customer-facing page, and a rich editor
   * is not what "type the terms in" needs.
   *
   * Empty English means the booking form shows no agreement tick at all —
   * asking someone to agree to nothing is worse than not asking.
   */
  termsEn: text("terms_en").notNull().default(""),
  /** Empty Arabic falls back to the English text rather than showing nothing. */
  termsAr: text("terms_ar").notNull().default(""),

  /**
   * Footer content overrides (migration 0015). Any key absent or empty falls
   * back to messages/*.json, so an untouched deployment renders the designed
   * footer and clearing a field restores the default rather than blanking it.
   */
  footer: jsonb("footer")
    .$type<Record<string, string>>()
    .notNull()
    .default({}),

  /**
   * FAQ (migration 0016), in display order. Empty falls back to the questions
   * in messages/*.json, so deleting every row restores the designed set rather
   * than emptying the section.
   */
  faq: jsonb("faq")
    .$type<
      {
        questionEn: string;
        questionAr: string;
        answerEn: string;
        answerAr: string;
      }[]
    >()
    .notNull()
    .default([]),

  updatedAt: timestamp("updated_at", { withTimezone: true })
    .notNull()
    .defaultNow(),
});


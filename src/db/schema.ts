import {
  pgTable,
  pgEnum,
  uuid,
  text,
  date,
  time,
  timestamp,
  integer,
  numeric,
  boolean,
  jsonb,
  inet,
  index,
  uniqueIndex,
} from "drizzle-orm/pg-core";

/**
 * YourWaves data model.
 *
 * Money is always an integer in minor units (see `price_*` below) — never a
 * float, never `numeric`. Booking days are always `date`, never `timestamp`;
 * see src/lib/dates.ts for why.
 *
 * The no-double-booking guarantee is NOT expressed here: it is a partial unique
 * index defined in drizzle/0001_booking_locking.sql, because Drizzle cannot
 * express a partial index over an enum list. That index — not application
 * code — is what makes overlapping bookings impossible.
 */

// --- Enums ------------------------------------------------------------------

/**
 * SRS 3.3 defines the customer-visible lifecycle:
 *   pending → confirmed → assigned → en_route → completed, plus cancelled.
 *
 * `holding` and `expired` are internal to the 10-minute checkout lock:
 * `holding` reserves the date while the customer pays; `expired` releases it.
 */
export const bookingStatus = pgEnum("booking_status", [
  "holding",
  "pending",
  "confirmed",
  "assigned",
  "en_route",
  "completed",
  "cancelled",
  "expired",
]);

/**
 * The statuses that occupy a date. Kept here as the single source of truth and
 * asserted against the database in tests, so this list and the partial unique
 * index in SQL can never silently diverge.
 */
export const BLOCKING_STATUSES = [
  "holding",
  "pending",
  "confirmed",
  "assigned",
  "en_route",
  "completed",
] as const;

export type BlockingStatus = (typeof BLOCKING_STATUSES)[number];
export type BookingStatus = (typeof bookingStatus.enumValues)[number];

export const actorType = pgEnum("actor_type", [
  "system",
  "admin",
  "customer",
  "driver",
]);

export const paymentStatus = pgEnum("payment_status", [
  "initiated",
  "paid",
  "failed",
  "refunded",
]);

export const notificationChannel = pgEnum("notification_channel", [
  "email",
  "whatsapp",
]);

export const notificationRecipientType = pgEnum("notification_recipient_type", [
  "customer",
  "admin",
  "driver",
]);

export const notificationStatus = pgEnum("notification_status", [
  "queued",
  "sent",
  "failed",
]);

// --- Dispatch recipients ----------------------------------------------------

/**
 * Anyone who can be sent a job by WhatsApp: the driver, the owner, a
 * supervisor, the technician.
 *
 * Was `drivers`, renamed in migration 0010. There is no driver login — the
 * `user_id` and `email` columns are gone with it — and a recipient flagged
 * `isDefault` is dispatched automatically the moment a booking is paid.
 */
export const dispatchRecipients = pgTable("dispatch_recipients", {
  id: uuid("id").primaryKey().defaultRandom(),
  fullName: text("full_name").notNull(),
  /** E.164. Unique since 0009: the number is the identity. */
  phone: text("phone").notNull(),
  role: text("role").notNull().default("driver"),
  /** Included on every newly confirmed booking, without an admin acting. */
  isDefault: boolean("is_default").notNull().default(false),
  isActive: boolean("is_active").notNull().default(true),
  createdAt: timestamp("created_at", { withTimezone: true })
    .notNull()
    .defaultNow(),
});

// --- Bookings ---------------------------------------------------------------

export const bookings = pgTable(
  "bookings",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    /**
     * Human-facing reference, e.g. "YW-2026-0417". Generated by
     * next_booking_reference() (see drizzle/0001_booking_locking.sql), which
     * restarts the counter each Qatar calendar year.
     */
    reference: text("reference").notNull().unique(),

    /** The FULL DAY being reserved. A calendar date — never a timestamp. */
    bookingDate: date("booking_date").notNull(),
    /** Customer's chosen setup time, Qatar wall clock. */
    preferredStart: time("preferred_start").notNull(),

    status: bookingStatus("status").notNull().default("pending"),
    /** Non-null only while status = 'holding'; enforced by a CHECK constraint. */
    holdExpiresAt: timestamp("hold_expires_at", { withTimezone: true }),

    customerName: text("customer_name").notNull(),
    /** E.164. */
    customerPhone: text("customer_phone").notNull(),
    customerEmail: text("customer_email"),
    phoneVerifiedAt: timestamp("phone_verified_at", { withTimezone: true }),

    addressLine: text("address_line").notNull(),
    area: text("area"),
    city: text("city"),
    /** Optional Google Maps link (SRS 3.1). */
    mapsUrl: text("maps_url"),
    lat: numeric("lat", { precision: 9, scale: 6 }),
    lng: numeric("lng", { precision: 9, scale: 6 }),

    notes: text("notes"),
    /** Language for ALL notifications sent to this customer. */
    locale: text("locale").notNull().default("ar"),

    // Money: minor units (1 QAR = 100 dirhams). Integers only.
    priceRental: integer("price_rental").notNull(),
    priceSetup: integer("price_setup").notNull(),
    priceDelivery: integer("price_delivery").notNull(),
    priceTotal: integer("price_total").notNull(),
    currency: text("currency").notNull().default("QAR"),

    assignedDriver: uuid("assigned_driver").references(
      () => dispatchRecipients.id,
      {
        onDelete: "set null",
      },
    ),

    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (table) => [
    // Availability lookups scan by date range and status.
    index("bookings_booking_date_idx").on(table.bookingDate),
    index("bookings_status_idx").on(table.status),
    index("bookings_hold_expires_at_idx").on(table.holdExpiresAt),
    index("bookings_customer_phone_idx").on(table.customerPhone),
  ],
);

// --- Booking events (immutable audit trail) ---------------------------------

export const bookingEvents = pgTable(
  "booking_events",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    bookingId: uuid("booking_id")
      .notNull()
      .references(() => bookings.id, { onDelete: "cascade" }),
    /** Null on the row recording creation. */
    fromStatus: bookingStatus("from_status"),
    toStatus: bookingStatus("to_status").notNull(),
    actorType: actorType("actor_type").notNull().default("system"),
    /** Admin/driver uuid, or a free-form id for customers. */
    actorId: text("actor_id"),
    metadata: jsonb("metadata").notNull().default({}),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (table) => [index("booking_events_booking_id_idx").on(table.bookingId)],
);

